-- 熄火 App 云端同步表（Supabase SQL Editor 执行一次即可）
create table if not exists public.smokes (
  id bigint generated by default as identity primary key,
  type text not null check (type in ('smoke','resist')),
  ts bigint not null,
  created_at timestamptz not null default now()
);
create index if not exists smokes_ts_idx on public.smokes (ts);
alter table public.smokes enable row level security;
drop policy if exists "anon all" on public.smokes;
create policy "anon all" on public.smokes for all using (true) with check (true);
